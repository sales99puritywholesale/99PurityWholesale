// Generates supabase/review/p3/seed-products.sql from src/data/products.json (the public catalog content). OFFLINE: reads one JSON file and writes one SQL file; it never connects
// to a database. NO prices are seeded: base_price_cents and min_price_cents stay NULL, so nothing is listed or purchasable until an administrator sets BOTH.
//
// Predictable updates (L5): the SQL is idempotent and re-runnable.
//   * products: a NEW slug is inserted. For an EXISTING slug the seed refreshes name, category, CAS and description ONLY while content_managed_by = 'seed' (content that
//     administrators took over is never touched), and never touches status. The WHERE clause makes this explicit.
//   * variants: a NEW sku is inserted. An existing sku is never updated (prices, status and anything an administrator maintains stay as they are).
//   * nothing is ever deleted, archived or re-published by the seed.
//
// Descriptions (M4): descriptions are SANITIZED sentence by sentence. A sentence is DROPPED when it contains marketing language (buy, shop, online, wholesale, "USA-manufactured",
// quality or purity claims, test or verification claims, "guaranteed") or any health, performance, appearance, aging or clinical claim or implication. Nothing is rewritten and no
// replacement text is invented; when no sentence survives, the description is NULL. Names, categories and CAS numbers are kept as they are in the public catalog data.
// Usage: node scripts/gen-catalog-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const products = JSON.parse(readFileSync('src/data/products.json', 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const slugRe = /^[a-z0-9][a-z0-9-]{0,100}$/;
const catRe = /^[a-z0-9-]{1,60}$/;

// marketing and claim vocabulary (conservative: a sentence with any of these is removed)
const DROP = [
  /\b(buy|buying|order|shop|purchase|sale|discount|cheap|best|premium|top[- ]quality|high[- ]quality|high[- ]purity|ultra[- ]pure|fast|free shipping|bulk)\b/i,
  /\bonline\b/i, /\bwholesale\b/i, /\busa\b/i, /\bmade in\b/i, /\bmanufactured\b/i, /\bguarantee/i, /\bpurity\b/i, /\bpure\b/i, /\bhplc\b/i, /\bverified\b/i,
  /\btested\b/i, /\btesting\b/i, /\bcertified\b/i, /\bcoa\b/i, /\d\s*%/, /\b99\b/,
  /anti-?aging|\baging\b|longevity|rejuvenat|youth|wellness|\bhealth|healing|\bheal\b|repair|recover|regenerat|\bglow|\bskin\b|\bhair\b|\bsleep|\bmood\b|\benergy\b/i,
  /weight|\bfat\b|lipo|slimming|appetite|muscle|growth|performance|strength|\bgains?\b|physique|\bbody\b/i,
  /treat|cure|therap|clinical|patient|prescription|inject|\bdos(e|age|ing)\b|\bdrug\b|\bmedic|\bdisease|\bpain\b|inflammat|\bcancer|diabet|obes|\bhuman\b|\bsafe\b|\bsafety\b|\bsuppl/i,
  /neuroprotect|cognitive|memory|focus|immune|metabolic|libido|sexual|hormone|cardio|vascular|fibro|tissue|remodel|senescen|telomer|angiogen|lipid|glucose|insulin/i,
];
const sanitize = (text) => {
  if (!text) return null;
  const kept = String(text).split(/(?<=[.!?])\s+/).map((s) => s.trim()).filter((s) => s && !DROP.some((re) => re.test(s)));
  const out = kept.join(' ').slice(0, 2000);
  return out || null;
};

const skus = new Set();
const slugs = new Set();
const rows = [];
const variantRows = [];
let described = 0;
let dropped = 0;
for (const p of products) {
  if (!slugRe.test(p.slug) || !catRe.test(p.category) || slugs.has(p.slug)) throw new Error(`bad or duplicate product: ${p.slug}`);
  slugs.add(p.slug);
  const d = sanitize(p.description);
  if (d) described++; else if (p.description) dropped++;
  rows.push(`(${q(p.slug)}, ${q(p.name.slice(0, 200))}, ${q(p.category)}, ${p.cas && p.cas !== 'N/A' ? q(String(p.cas).slice(0, 40)) : 'null'}, ${d ? q(d) : 'null'})`);
  for (const spec of p.specs ?? []) {
    const sku = `${p.slug}-${spec}`.toUpperCase().replace(/×/g, 'X').replace(/[^A-Z0-9.]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 64);
    if (!/^[A-Z0-9][A-Z0-9._-]{2,63}$/.test(sku) || skus.has(sku)) throw new Error(`bad or duplicate sku: ${sku}`);
    skus.add(sku);
    variantRows.push(`(${q(p.slug)}, ${q(String(spec).slice(0, 60))}, ${q(sku)})`);
  }
}
const sql = `-- GENERATED by scripts/gen-catalog-seed.mjs from src/data/products.json. NOT APPLIED. Apply only after the P3 migration and only with the project owner's approval.
-- ${products.length} products, ${variantRows.length} variants. NO prices are seeded (base_price_cents and min_price_cents stay NULL: a variant is not listed or purchasable until an administrator sets BOTH).
-- ${described} descriptions kept after sanitizing (marketing, quality, testing and health-related sentences removed, nothing invented), ${products.length - described} descriptions empty.
-- Re-running is safe: new products and variants are inserted; existing products are refreshed ONLY while content_managed_by = 'seed'; existing variants (prices, status) are never touched; nothing is deleted.
insert into public.products (slug, name, category, cas, description) values
${rows.join(',\n')}
on conflict (slug) do update
  set name = excluded.name, category = excluded.category, cas = excluded.cas, description = excluded.description
  where public.products.content_managed_by = 'seed';

insert into public.product_variants (product_id, spec, sku)
select p.id, v.spec, v.sku
  from (values
${variantRows.join(',\n')}
  ) as v(slug, spec, sku)
  join public.products p on p.slug = v.slug
on conflict (sku) do nothing;
`;
writeFileSync('supabase/review/p3/seed-products.sql', sql);
console.log(`${products.length} products, ${variantRows.length} variants, ${described} descriptions kept, ${dropped} dropped entirely, sha256 ${createHash('sha256').update(sql).digest('hex')}`);
