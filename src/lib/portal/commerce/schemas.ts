import { z } from 'zod';
import { MAX_FIXED_E4, MAX_LINE_QUANTITY, MAX_PERCENT_E4, MAX_PRICE_CENTS } from './pricing';
import { ORDER_STATUSES } from './orders';

/** Input validation for P3 server actions. Strict objects; every id is a UUID; nothing here is trusted for price. */
export const uuid = z.string().uuid();
const text = (max: number) => z.string().trim().min(1).max(max);

export const cartSetItemSchema = z.object({ organizationId: uuid, variantId: uuid, quantity: z.number().int().min(0).max(MAX_LINE_QUANTITY) }).strict();

export const shipToSchema = z
  .object({
    name: text(120),
    line1: text(160),
    line2: z.string().trim().max(160).optional(),
    city: text(80),
    region: text(80),
    postal: text(20),
    country: z.string().trim().regex(/^[A-Z]{2}$/),
  })
  .strict();

/** idempotencyKey: generated by the server for each rendered checkout form; a repeated submit with the same key returns the same order. */
export const checkoutSchema = z
  .object({ organizationId: uuid, shipTo: shipToSchema, notes: z.string().trim().max(500).optional(), idempotencyKey: uuid })
  .strict();

/** Base price and floor: both must be set (positive) for the variant to be listed or sold; either may be cleared. */
export const setVariantPriceSchema = z
  .object({
    variantId: uuid,
    baseCents: z.number().int().min(1).max(MAX_PRICE_CENTS).nullable(),
    floorCents: z.number().int().min(1).max(MAX_PRICE_CENTS).nullable(),
  })
  .strict();

const e4 = (max: number) => z.number().int().min(0).max(max).nullable();
/** One markup rule (Aspen admin_set_markup_rule). Values are integers in units of 1e-4 (percent x 10000, or dollars x 10000 for a fixed amount). */
export const markupRuleSchema = z
  .object({
    organizationId: uuid,
    kind: z.enum(['organization', 'representative']),
    productId: uuid.nullable(),
    type: z.enum(['percent', 'fixed']),
    valueE4: z.number().int().min(0).max(MAX_FIXED_E4),
    repMinPercentE4: e4(MAX_PERCENT_E4),
    repMaxPercentE4: e4(MAX_PERCENT_E4),
    repMinFixedE4: e4(MAX_FIXED_E4),
    repMaxFixedE4: e4(MAX_FIXED_E4),
    active: z.boolean(),
  })
  .strict()
  .refine((r) => r.type === 'fixed' || r.valueE4 <= MAX_PERCENT_E4, { message: 'percent above 1000', path: ['valueE4'] })
  .refine((r) => r.kind === 'organization' || [r.repMinPercentE4, r.repMaxPercentE4, r.repMinFixedE4, r.repMaxFixedE4].every((v) => v === null), { message: 'bounds are for organization rules only' })
  .refine((r) => r.repMinPercentE4 === null || r.repMaxPercentE4 === null || r.repMinPercentE4 <= r.repMaxPercentE4, { message: 'percent bounds order' })
  .refine((r) => r.repMinFixedE4 === null || r.repMaxFixedE4 === null || r.repMinFixedE4 <= r.repMaxFixedE4, { message: 'fixed bounds order' });

export const orgProductSchema = z.object({ organizationId: uuid, productId: uuid, assigned: z.boolean(), available: z.boolean() }).strict();

export const orderStatusSchema = z.object({ orderId: uuid, to: z.enum(ORDER_STATUSES), note: z.string().trim().max(300).optional() }).strict();
